CREATE DATABASE IF NOT EXISTS placement_portal CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE placement_portal;

CREATE TABLE users (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(180) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL, role ENUM('STUDENT','ADMIN','COMPANY') NOT NULL DEFAULT 'STUDENT', phone VARCHAR(25),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE student_profiles (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL UNIQUE, roll_number VARCHAR(50) UNIQUE,
  branch VARCHAR(100), cgpa DECIMAL(3,2), graduation_year SMALLINT, date_of_birth DATE, location VARCHAR(120),
  github_url VARCHAR(255), linkedin_url VARCHAR(255), portfolio_url VARCHAR(255), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_profile_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE skills (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(100) NOT NULL UNIQUE, category VARCHAR(80) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE student_skills (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id BIGINT UNSIGNED NOT NULL, skill_id BIGINT UNSIGNED NOT NULL,
  proficiency_level ENUM('BEGINNER','INTERMEDIATE','ADVANCED') NOT NULL DEFAULT 'INTERMEDIATE', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_student_skill(student_id,skill_id), CONSTRAINT fk_ss_profile FOREIGN KEY(student_id) REFERENCES student_profiles(id) ON DELETE CASCADE,
  CONSTRAINT fk_ss_skill FOREIGN KEY(skill_id) REFERENCES skills(id) ON DELETE CASCADE
);
CREATE TABLE education (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id BIGINT UNSIGNED NOT NULL, degree VARCHAR(120) NOT NULL,
  institution VARCHAR(180) NOT NULL, field VARCHAR(120), start_year SMALLINT, end_year SMALLINT, cgpa DECIMAL(3,2),
  CONSTRAINT fk_education_profile FOREIGN KEY(student_id) REFERENCES student_profiles(id) ON DELETE CASCADE
);
CREATE TABLE projects (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id BIGINT UNSIGNED NOT NULL, title VARCHAR(160) NOT NULL, description TEXT,
  technologies TEXT, github_url VARCHAR(255), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_project_profile FOREIGN KEY(student_id) REFERENCES student_profiles(id) ON DELETE CASCADE
);
CREATE TABLE certifications (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id BIGINT UNSIGNED NOT NULL, name VARCHAR(160) NOT NULL,
  issuing_organization VARCHAR(160), issue_date DATE, credential_url VARCHAR(255),
  CONSTRAINT fk_cert_profile FOREIGN KEY(student_id) REFERENCES student_profiles(id) ON DELETE CASCADE
);
CREATE TABLE internships (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id BIGINT UNSIGNED NOT NULL, company VARCHAR(160) NOT NULL,
  role VARCHAR(120), description TEXT, start_date DATE, end_date DATE,
  CONSTRAINT fk_internship_profile FOREIGN KEY(student_id) REFERENCES student_profiles(id) ON DELETE CASCADE
);
CREATE TABLE resumes (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id BIGINT UNSIGNED NOT NULL, file_name VARCHAR(255) NOT NULL,
  file_path VARCHAR(500) NOT NULL, extracted_text LONGTEXT, uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_resume_profile FOREIGN KEY(student_id) REFERENCES student_profiles(id) ON DELETE CASCADE
);
CREATE TABLE resume_analysis (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, resume_id BIGINT UNSIGNED NOT NULL UNIQUE, extracted_skills JSON,
  education JSON, experience JSON, projects JSON, certifications JSON, ats_score TINYINT UNSIGNED, score_breakdown JSON,
  missing_skills JSON, recommendations JSON, analyzed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_analysis_resume FOREIGN KEY(resume_id) REFERENCES resumes(id) ON DELETE CASCADE
);
CREATE TABLE companies (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL UNIQUE, company_name VARCHAR(160) NOT NULL,
  description TEXT, website VARCHAR(255), location VARCHAR(120), created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_company_user FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE jobs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, company_id BIGINT UNSIGNED NOT NULL, title VARCHAR(160) NOT NULL, description TEXT NOT NULL,
  required_skills JSON NOT NULL, minimum_cgpa DECIMAL(3,2) DEFAULT 0, eligible_branches JSON, graduation_year SMALLINT, salary VARCHAR(100),
  location VARCHAR(120), job_type ENUM('FULL_TIME','INTERNSHIP','PART_TIME','CONTRACT') DEFAULT 'FULL_TIME', deadline DATE, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_jobs_company(company_id), INDEX idx_jobs_deadline(deadline), CONSTRAINT fk_job_company FOREIGN KEY(company_id) REFERENCES companies(id) ON DELETE CASCADE
);
CREATE TABLE job_applications (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id BIGINT UNSIGNED NOT NULL, job_id BIGINT UNSIGNED NOT NULL,
  status ENUM('APPLIED','SHORTLISTED','INTERVIEW','SELECTED','REJECTED') NOT NULL DEFAULT 'APPLIED', applied_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, UNIQUE KEY uq_application(student_id,job_id),
  INDEX idx_application_status(status), CONSTRAINT fk_app_profile FOREIGN KEY(student_id) REFERENCES student_profiles(id) ON DELETE CASCADE,
  CONSTRAINT fk_app_job FOREIGN KEY(job_id) REFERENCES jobs(id) ON DELETE CASCADE
);
CREATE TABLE placement_predictions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id BIGINT UNSIGNED NOT NULL, probability DECIMAL(5,2) NOT NULL,
  prediction_label ENUM('LOW','MEDIUM','HIGH') NOT NULL, confidence DECIMAL(5,2), important_factors JSON, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_prediction_profile(student_id,created_at), CONSTRAINT fk_prediction_profile FOREIGN KEY(student_id) REFERENCES student_profiles(id) ON DELETE CASCADE
);
CREATE TABLE assessments (id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, title VARCHAR(160) NOT NULL, category VARCHAR(80) NOT NULL, difficulty ENUM('EASY','MEDIUM','HARD') NOT NULL DEFAULT 'MEDIUM', duration_minutes SMALLINT DEFAULT 20, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE questions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, assessment_id BIGINT UNSIGNED NOT NULL, question TEXT NOT NULL, option_a VARCHAR(500) NOT NULL, option_b VARCHAR(500) NOT NULL, option_c VARCHAR(500) NOT NULL, option_d VARCHAR(500) NOT NULL, correct_answer ENUM('A','B','C','D') NOT NULL,
  CONSTRAINT fk_question_assessment FOREIGN KEY(assessment_id) REFERENCES assessments(id) ON DELETE CASCADE
);
CREATE TABLE assessment_results (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id BIGINT UNSIGNED NOT NULL, assessment_id BIGINT UNSIGNED NOT NULL, score SMALLINT NOT NULL, percentage DECIMAL(5,2) NOT NULL, completed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_result_profile(student_id), CONSTRAINT fk_result_profile FOREIGN KEY(student_id) REFERENCES student_profiles(id) ON DELETE CASCADE,
  CONSTRAINT fk_result_assessment FOREIGN KEY(assessment_id) REFERENCES assessments(id) ON DELETE CASCADE
);
CREATE TABLE interview_questions (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, role VARCHAR(120) NOT NULL, category VARCHAR(80) NOT NULL, difficulty ENUM('EASY','MEDIUM','HARD') DEFAULT 'MEDIUM', question TEXT NOT NULL, ideal_answer TEXT NOT NULL, key_concepts JSON, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_interview_role(role,category)
);
CREATE TABLE interview_progress (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, student_id BIGINT UNSIGNED NOT NULL, question_id BIGINT UNSIGNED NOT NULL, status ENUM('NOT_STARTED','PRACTICED','MASTERED') DEFAULT 'NOT_STARTED', score TINYINT UNSIGNED, feedback TEXT, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_interview_progress(student_id,question_id), CONSTRAINT fk_ip_profile FOREIGN KEY(student_id) REFERENCES student_profiles(id) ON DELETE CASCADE,
  CONSTRAINT fk_ip_question FOREIGN KEY(question_id) REFERENCES interview_questions(id) ON DELETE CASCADE
);
